#!/usr/bin/env python3
"""
Refreshes the translation files after changing texts in the module.

  python3 i18n/update.py

1. Extracts the _('...') strings from the PHP files and the T('...') strings from assets/js/*.js
   into i18n/ciscosipmanager.pot (needs xgettext from GNU gettext).
2. Writes lib/JsStrings.php with the JS strings, so FreePBX translates them through gettext.
3. Merges the template into every i18n/<lang>/LC_MESSAGES/ciscosipmanager.po (msgmerge) and
   compiles the .mo files (msgfmt). New strings show up untranslated in the .po; translate them
   and run the script again.

To add a language: mkdir -p i18n/<lang>/LC_MESSAGES, copy ciscosipmanager.pot there as
ciscosipmanager.po, translate it and run the script. FreePBX picks the folder by the language
code (es, fr, pt_BR...).
"""
import glob
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

PHP_FILES = sorted(f for f in glob.glob('*.php') + glob.glob('lib/*.php') + glob.glob('views/*.php') if f != 'lib/JsStrings.php')
JS_FILES = sorted(glob.glob('assets/js/*.js'))
POT = 'i18n/ciscosipmanager.pot'


def run(*cmd):
    subprocess.check_call(cmd)


def msgids(pot):
    """msgid values of a .pot written with --no-wrap"""
    out = []
    for m in re.finditer(r'^msgid "(.*)"$', open(pot, encoding='utf-8').read(), re.M):
        s = m.group(1)
        if s:
            s = s.replace('\\"', '"').replace('\\n', '\n').replace('\\t', '\t').replace('\\\\', '\\')
            out.append(s)
    return out


def phpq(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


with tempfile.TemporaryDirectory() as tmp:
    jspot = os.path.join(tmp, 'js.pot')
    run('xgettext', '-L', 'JavaScript', '--from-code=UTF-8', '--no-wrap', '-kT', '-o', jspot, *JS_FILES)
    js = sorted(set(msgids(jspot)))

with open('lib/JsStrings.php', 'w', encoding='utf-8') as fh:
    fh.write("<?php\n/**\n * Strings used by assets/js/ciscosipmanager.js, translated with gettext.\n"
             " * views/_nav.php prints them as window.csmI18n. Generated by i18n/update.py: do not edit by hand.\n */\n"
             "namespace FreePBX\\modules\\Ciscosipmanager;\n\nclass JsStrings\n{\n\tpublic static function get()\n\t{\n\t\treturn [\n")
    for s in js:
        fh.write('\t\t\t%s => _(%s),\n' % (phpq(s), phpq(s)))
    fh.write('\t\t];\n\t}\n}\n')

version = re.search(r'<version>([^<]+)</version>', open('module.xml', encoding='utf-8').read()).group(1)
run('xgettext', '-L', 'PHP', '--from-code=UTF-8', '--no-wrap', '-k_', '--add-comments=TRANSLATORS',
    '--package-name=ciscosipmanager', '--package-version=' + version,
    '--msgid-bugs-address=https://github.com/jorgedsan/Cisco_SIP_Manager/issues',
    '-o', POT, *PHP_FILES, 'lib/JsStrings.php')
run('xgettext', '-L', 'JavaScript', '--from-code=UTF-8', '--no-wrap', '-kT', '-j', '-o', POT, *JS_FILES)
# Template header: xgettext leaves placeholders, and the -j pass resets the package name
pot = open(POT, encoding='utf-8').read()
head, body = pot.split('\n\n', 1)
head = re.sub(r'^(# .*\n)+#\n', '# Cisco SIP Manager for FreePBX: translation template.\n# This file is distributed under the same license as the module (GPLv3+).\n#\n', head + '\n', count=1).rstrip('\n')
head = re.sub(r'"Project-Id-Version: .*\\n"', '"Project-Id-Version: ciscosipmanager %s\\\\n"' % version, head)
head = re.sub(r'"Report-Msgid-Bugs-To: .*\\n"', '"Report-Msgid-Bugs-To: https://github.com/jorgedsan/Cisco_SIP_Manager/issues\\\\n"', head)
head = head.replace('charset=CHARSET', 'charset=UTF-8')
open(POT, 'w', encoding='utf-8').write(head + '\n\n' + body)

for po in sorted(glob.glob('i18n/*/LC_MESSAGES/ciscosipmanager.po')):
    run('msgmerge', '--quiet', '--no-wrap', '--no-fuzzy-matching', '--backup=none', '-U', po, POT)
    run('msgattrib', '--no-wrap', '--no-obsolete', '-o', po, po)
    run('msgfmt', '-c', '-o', po[:-3] + '.mo', po)
    stats = subprocess.run(['msgfmt', '--statistics', '-o', os.devnull, po], capture_output=True, text=True).stderr.strip()
    print(po + ': ' + stats)

print('%d JS strings, template %s' % (len(js), POT))
